"""Plan → trigger-manifest emission (plan --emit-manifest)."""

import json
import re

import pytest
from devin_orchestrator.cli import main
from devin_orchestrator.emit import (
    MANIFEST_ID_RE,
    SCHEDULE_RE,
    manifest_to_json,
    manifest_to_yaml,
    plan_manifest,
)
from devin_orchestrator.planner import plan_task

SPEC = (
    '{"kind":"implementation","independent_units":2,"estimated_scope":'
    '"medium","summary":"api + ui","units_detail":[{"id":"api"},'
    '{"id":"ui"}]}'
)

# Field contract mirrored from .devin/catalog/trigger.schema.json
# (devin-skill-catalog §8) — kept literal so drift here is visible.
REQUIRED_KEYS = {
    "id", "version", "owner", "severity", "class", "trigger", "action"}
CLASSES = {"gate", "corrector", "observer", "enricher"}
SCOPES = {"session", "repository", "workspace", "global", "artifact"}
EVENT_RE = re.compile(r"^[A-Z][A-Za-z0-9]*$")


def _spec():
    return json.loads(SPEC)


def _extract_command(yaml_text: str) -> str:
    """Pull the single-quoted action.command out of emitted YAML."""
    m = re.search(r"^  command: '(.*)'$", yaml_text, re.MULTILINE)
    assert m, "command line not found in manifest"
    return m.group(1).replace("''", "'")


def _manifest_command_spec(command: str) -> dict:
    assert command.startswith("devin-orchestrator plan '")
    assert command.endswith("'")
    return json.loads(command[len("devin-orchestrator plan '"):-1])


# -- manifest construction ---------------------------------------------------


def test_plan_manifest_fields_match_catalog_schema():
    spec = _spec()
    m = plan_manifest(spec, plan_task(spec))
    assert REQUIRED_KEYS <= set(m)
    assert MANIFEST_ID_RE.match(m["id"])
    assert m["id"].startswith("orchestrator.plan-")
    assert m["version"] == 1 and isinstance(m["version"], int)
    assert m["enabled"] is True
    assert m["severity"] in {"p0", "p1", "p2"}
    assert m["class"] in CLASSES
    assert EVENT_RE.match(m["trigger"]["event"])
    assert m["trigger"]["scope"] in SCOPES
    assert SCHEDULE_RE.match(m["trigger"]["schedule"])
    assert m["action"]["mode"] in {"sync", "async"}
    assert 1 <= m["action"]["timeout"] <= 600
    # catalog rule: Scheduled constant input must disable idempotency
    assert m["idempotency"] == {"disabled": True}
    assert m["on_hook_failure"] in {"fail-open", "fail-closed"}


def test_plan_manifest_id_is_deterministic_and_overridable():
    spec = _spec()
    a = plan_manifest(spec, plan_task(spec))
    b = plan_manifest(spec, plan_task(spec))
    assert a["id"] == b["id"]
    custom = plan_manifest(spec, plan_task(spec),
                           manifest_id="myteam.nightly-fanout")
    assert custom["id"] == "myteam.nightly-fanout"
    with pytest.raises(ValueError, match="manifest id"):
        plan_manifest(spec, plan_task(spec), manifest_id="Bad Id!")


def test_plan_manifest_schedule_validation():
    spec = _spec()
    for ok in ["every 30m", "every 2h", "hourly", "daily", "daily 05:30",
               "weekly sun", "weekly mon 3:00"]:
        m = plan_manifest(spec, plan_task(spec), schedule=ok)
        assert m["trigger"]["schedule"] == ok
    for bad in ["", "every 5d", "daily 25:99", "mondays", "soon"]:
        with pytest.raises(ValueError, match="schedule"):
            plan_manifest(spec, plan_task(spec), schedule=bad)


def test_plan_manifest_non_scheduled_event_has_no_schedule():
    spec = _spec()
    m = plan_manifest(spec, plan_task(spec), event="SessionSweep",
                      schedule=None)
    assert m["trigger"] == {"event": "SessionSweep", "scope": "workspace"}
    with pytest.raises(ValueError, match="only applies to event"):
        plan_manifest(spec, plan_task(spec), event="SessionSweep",
                      schedule="daily")


def test_manifest_action_is_single_readonly_job_description():
    spec = _spec()
    m = plan_manifest(spec, plan_task(spec))
    cmd = m["action"]["command"]
    # one orchestrator invocation carrying the canonical spec — the
    # units ride inside the JSON argument, never as shell fragments
    assert cmd.count("devin-orchestrator") == 1
    carried = _manifest_command_spec(cmd)
    assert carried["units_detail"] == spec["units_detail"]
    assert "|" not in cmd and ";" not in cmd and "&&" not in cmd


# -- yaml serialization --------------------------------------------------------


def test_manifest_to_yaml_round_trips_units():
    spec = _spec()
    plan = plan_task(spec)
    text = manifest_to_yaml(plan_manifest(spec, plan), plan)
    assert text.startswith("# Generated by devin-orchestrator")
    assert "event: Scheduled" in text
    carried = _manifest_command_spec(_extract_command(text))
    assert carried == spec  # round-trip: same units, same spec


def test_manifest_to_yaml_escapes_quotes():
    spec = {"kind": "implementation", "independent_units": 2,
            "summary": "it's a test"}
    text = manifest_to_yaml(plan_manifest(spec, plan_task(spec)))
    assert "it''s a test" in text
    carried = _manifest_command_spec(_extract_command(text))
    assert carried["summary"] == "it's a test"


def test_manifest_to_json_is_catalog_loadable():
    spec = _spec()
    m = json.loads(manifest_to_json(plan_manifest(spec, plan_task(spec))))
    assert REQUIRED_KEYS <= set(m)
    assert m["trigger"]["event"] == "Scheduled"


# -- cli -----------------------------------------------------------------------


def test_cli_emit_manifest_yaml_stdout(capsys):
    rc = main(["plan", SPEC, "--emit-manifest"])
    assert rc == 0
    out = capsys.readouterr().out
    assert "id: orchestrator.plan-" in out
    assert "devin-orchestrator plan '" in out
    carried = _manifest_command_spec(_extract_command(out))
    assert carried["independent_units"] == 2


def test_cli_emit_manifest_json(capsys):
    rc = main(["plan", SPEC, "--emit-manifest", "--format", "json"])
    assert rc == 0
    m = json.loads(capsys.readouterr().out)
    assert REQUIRED_KEYS <= set(m)


def test_cli_emit_manifest_to_file(tmp_path, capsys):
    target = tmp_path / "nightly.yaml"
    rc = main(["plan", SPEC, "--emit-manifest", "--out", str(target)])
    assert rc == 0
    assert capsys.readouterr().out == ""
    text = target.read_text(encoding="utf-8")
    assert "id: orchestrator.plan-" in text


def test_cli_emit_manifest_rejects_flag_combinations(capsys):
    assert main(["plan", SPEC, "--emit-manifest", "--explain"]) == 2
    assert "--emit-manifest" in capsys.readouterr().err
    assert main(["plan", SPEC, "--emit-manifest", "--cost-estimate"]) == 2
    capsys.readouterr()
    # manifest-only flags without --emit-manifest
    for extra in [["--schedule", "daily"], ["--manifest-id", "a.b"],
                  ["--out", "x.yaml"], ["--format", "json"],
                  ["--severity", "p1"], ["--manifest-event", "X"]]:
        assert main(["plan", SPEC] + extra) == 2
        assert "--emit-manifest" in capsys.readouterr().err


def test_cli_emit_manifest_bad_schedule_errors(capsys):
    assert main(["plan", SPEC, "--emit-manifest",
                 "--schedule", "whenever"]) == 2
    assert "schedule" in capsys.readouterr().err


def test_cli_emit_manifest_custom_event(capsys):
    rc = main(["plan", SPEC, "--emit-manifest",
               "--manifest-event", "SessionSweep"])
    assert rc == 0
    out = capsys.readouterr().out
    assert "event: SessionSweep" in out
    assert "schedule:" not in out
